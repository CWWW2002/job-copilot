from app.services.llm_client import complete

MAX_RESUME_CHARS = 6000
MAX_JD_CHARS = 4000

US_STYLE_RULES = """请按北美简历规范输出:
- 不包含照片、年龄、婚姻状况等个人信息
- 每条经历尽量用STAR结构改写,句子以动词开头(如 Led / Implemented / Optimized / Built)
- 如果原简历中已有具体数字(百分比、指标等),保留并突出;如果原简历没有具体数字,绝对不能编造数字,只能把原有描述改写成更符合动词开头、STAR结构的句式
- 语言简洁,避免堆砌形容词
- 绝对不使用Markdown表格语法(不允许出现任何 | 分隔的表格),全文单栏排版,用标题(##)+项目符号(-)或段落来表示层级和结构,不使用图标或任何ATS系统读取不了的格式"""

CHINA_STYLE_RULES = """请按中国大陆简历规范输出:
- 教育背景信息可以详细保留(学校、专业、排名等),放在比较靠前/权重较高的位置
- 语言表述要强调与目标职位、目标职级的匹配度
- 排版上可以使用简单的分栏或Markdown表格来呈现教育背景、技能清单等结构化信息,但表格使用有严格约束:
  - 只有当确实有至少一行真实数据可以填入时,才生成表格,且表头下面必须紧跟至少一行数据
  - 绝对不允许生成只有表头、没有任何数据行的空表格
  - 如果某个字段原简历完全没有对应信息、连占位符都不足以撑起一整行表格数据,就直接用文字段落或"- "项目符号表示,不要为了排版好看强行生成表格"""

MARKET_STYLE_RULES = {"us": US_STYLE_RULES, "china": CHINA_STYLE_RULES}


class TailorGenerationError(Exception):
    pass


def build_tailor_prompt(resume_text: str, jd_text: str, market_style: str) -> str:
    style_rules = MARKET_STYLE_RULES.get(market_style, US_STYLE_RULES)

    return f"""你是一位专业的求职简历顾问。请基于用户的原始简历和目标职位描述(JD),生成一份针对这个JD定制过的简历。

核心原则(必须严格遵守,优先级高于下面的排版规则):
1. 绝对不能编造用户没有的经历、技能、数据、协作细节、职责范围或任何具体事实。只能对已有内容重新组织、精简、换一种更贴近目标岗位的角度表述。
2. 严禁编造签证/工作授权状态(如OPT/CPT/H1B/绿卡/公民身份/户口/社保缴纳情况等)。原简历中没有明确提到的,生成的简历里也绝对不能出现——哪怕JD明确要求这项信息,也只能不写,不能替用户编一个。
3. 如果原简历某处信息不完整(如具体公司地点、任职时间、项目细节),需要占位时用方括号标注,例如 [公司所在城市]、[起止时间],不要用看似确定的语气编造这些内容。
4. 优先提取、强化简历中与JD相关的经历和技能;与JD关联度低的内容可以精简或弱化(不必删除,但不要占据主要篇幅)。
5. 如果用户过往经历的岗位类型与目标岗位不完全一致(例如做过运营、目标是产品岗),要主动识别两者之间的共通能力(如数据分析、跨团队协作、用户理解等),并用更贴近目标岗位语言习惯的措辞重新表述这些已有经历——但只能重新措辞原简历中已经存在的事实,不能加入原简历没有描述过的协作对象、沟通过程或职责。
6. 保留原文对个人角色的界定:原文写"协助""参与""编写"的,不能升级为"负责""主导""独立完成""Owned""Led"等更高级别的说法;原文是团队项目的,不能写成个人独立完成。
7. 不得给原有经历添加原文没有写过的效果、目的、影响或工作范围(例如原文只写"修复缺陷",不能补上"提升系统稳定性";原文只写"训练模型",不能扩写成"覆盖数据预处理、训练、评估全流程")。
8. 如果生成个人总结、核心优势等概括性段落,其中每一个说法都必须能在原简历的具体经历中找到对应依据;不能写"具备XX全流程经验""0→1操盘经验"这类原文撑不起来的概括,也不能列出原文没有的技能(包括"正在学习"之类的表述)。

{style_rules}

请直接输出定制后的简历全文(Markdown格式纯文本),不要输出任何解释、前言或后记,不要用代码块包裹。

原始简历:
---
{resume_text[:MAX_RESUME_CHARS]}
---

目标职位描述(JD):
---
{jd_text[:MAX_JD_CHARS]}
---
"""


def generate_tailored_resume(resume_text: str, jd_text: str, market_style: str) -> str:
    prompt = build_tailor_prompt(resume_text, jd_text, market_style)
    content = complete("tailor", prompt, max_tokens=3000).strip()
    if not content:
        raise TailorGenerationError("LLM未返回任何内容")
    return content
